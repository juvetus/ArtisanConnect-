export type TranslationKey = keyof typeof TRANSLATIONS.fr | keyof typeof SUPPLEMENTAL_TRANSLATIONS.fr;

export function getTranslation(lang: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.fr;
  const supplemental = SUPPLEMENTAL_TRANSLATIONS[lang] || SUPPLEMENTAL_TRANSLATIONS.fr;
  let text: string = (dict as Record<string, string>)[key]
    || (supplemental as Record<string, string>)[key]
    || (TRANSLATIONS.fr as Record<string, string>)[key]
    || (SUPPLEMENTAL_TRANSLATIONS.fr as Record<string, string>)[key]
    || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
}
